static const char *stress_branch_jumps(const size_t i)
{
	static char str[16];

	/* 0 -> 64, 1 -> 128, .. 5 -> 2048 */

	if (i <= 5) {
		(void)snprintf(str, sizeof(str), "%u", 64U << i);
		return str;
	}
	return NULL;
}

static const stress_opt_t opts[] = {
	{ OPT_branch_jumps, "branch-jumps", TYPE_ID_SIZE_T_METHOD, 0, 0, stress_branch_jumps },
        END_OPT,
};

